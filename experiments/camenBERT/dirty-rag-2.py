def split_sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"[.!?]+", text) if s.strip()]


def cosine(a, b) -> float:
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))


def semantic_chunk_turn(
    text: str,
    model,
    turn_id: int,
    drop_threshold: float = -0.10,
) -> list[dict]:
    sentences = split_sentences(text)

    if len(sentences) == 0:
        return []

    if len(sentences) == 1:
        return [
            {
                "turn_id": turn_id,
                "chunk_id": 0,
                "text": sentences[0],
            }
        ]

    sentence_embeddings = model.encode(sentences)

    cosarr = [
        cosine(sentence_embeddings[i], sentence_embeddings[i + 1])
        for i in range(len(sentences) - 1)
    ]

    breakpoints = []

    for i in range(1, len(cosarr)):
        delta = cosarr[i] - cosarr[i - 1]

        if delta < drop_threshold:
            breakpoints.append(i + 1)

    chunks = []
    start = 0
    chunk_id = 0

    for bp in breakpoints:
        chunks.append(
            {
                "turn_id": turn_id,
                "chunk_id": chunk_id,
                "text": ". ".join(sentences[start:bp]) + ".",
            }
        )
        start = bp
        chunk_id += 1

    chunks.append(
        {
            "turn_id": turn_id,
            "chunk_id": chunk_id,
            "text": ". ".join(sentences[start:]) + ".",
        }
    )

    return chunks


def build_chunk_db(raw_texts: list[str], model) -> list[dict]:
    chunk_db = []

    for turn_id, text in enumerate(raw_texts):
        chunks = semantic_chunk_turn(
            text=text,
            model=model,
            turn_id=turn_id,
            drop_threshold=-0.10,  # completly random threshold
        )
        chunk_db.extend(chunks)

    return chunk_db


MIN_WORDS = 8


def search_chunks(
    query: str,
    chunk_db: list[dict],
    chunk_embeddings,
    model,
    top_k: int = 5,
):
    query_embedding = model.encode(
        query,
        normalize_embeddings=True,
    )

    # dirty heuristic
    valid_indices = []

    for idx, chunk in enumerate(chunk_db):
        word_count = len(chunk["text"].split())

        if word_count >= MIN_WORDS:
            valid_indices.append(idx)

    valid_embeddings = chunk_embeddings[valid_indices]

    scores = valid_embeddings @ query_embedding

    best_local_ids = np.argsort(scores)[::-1][:top_k]

    for local_idx in best_local_ids:
        real_idx = valid_indices[local_idx]
        chunk = chunk_db[real_idx]

        print("=" * 80)
        print(
            f"turn={chunk['turn_id']} "
            f"chunk={chunk['chunk_id']} "
            f"score={scores[local_idx]:.4f}"
        )
        print(chunk["text"])

    turn_scores = defaultdict(float)
    turn_hits = defaultdict(list)

    for local_idx in best_local_ids:
        real_idx = valid_indices[local_idx]
        chunk = chunk_db[real_idx]
        score = float(scores[local_idx])
        turn_id = chunk["turn_id"]

        turn_scores[turn_id] += score

        turn_hits[turn_id].append(
            {
                "chunk_id": chunk["chunk_id"],
                "score": score,
                "text": chunk["text"],
            }
        )

    best_turn_id = max(turn_scores, key=turn_scores.get)  # type: ignore

    print("=" * 80)
    print(f"BEST TURN: {best_turn_id}")
    print(f"CUMULATED SCORE: {turn_scores[best_turn_id]:.4f}")
    print("*" * 10)
    print(raw_texts[best_turn_id])
    print("*" * 10)
    print("MATCHING CHUNKS:")

    for hit in turn_hits[best_turn_id]:
        print("-" * 40)
        print(f"chunk={hit['chunk_id']} score={hit['score']:.4f}")
        print(hit["text"])


